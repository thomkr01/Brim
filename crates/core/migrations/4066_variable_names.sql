-- Message variables take one scheme (owner rule 2026-11-23). A Discord thing has Discord's API
-- name (`{guild.name}`, `{member.id}`); Brim's own variables are `function_name`
-- (`{ga_prize}`, `{tk_type}`). The old names are not kept, so every saved text is rewritten here:
-- whole `{name}` tokens only, never other text. Running it twice changes nothing (no new name is
-- an old name of the same entry; a test in `botmsg.rs` keeps that true).

-- Fields of a server that said `server` (`OLD_FIELDS` in `botmsg.rs`): Message Builder and bot
-- message texts both use them.
CREATE OR REPLACE FUNCTION pg_temp.guild_names(t TEXT) RETURNS TEXT LANGUAGE sql IMMUTABLE AS $$
    SELECT replace(replace(replace(replace(replace(replace(replace(replace(t,
        '{server.name}', '{guild.name}'),
        '{server.id}', '{guild.id}'),
        '{server.member_count}', '{guild.member_count}'),
        '{server.boost_count}', '{guild.premium_subscription_count}'),
        '{server.boost_level}', '{guild.premium_tier}'),
        '{server.owner}', '{guild.owner_id}'),
        '{server.icon}', '{guild.icon}'),
        '{server.created_at}', '{guild.created_at}')
$$;

-- Message Builder texts: the fields above, and its own variables, which take the `msg_` prefix.
CREATE OR REPLACE FUNCTION pg_temp.builder_names(t TEXT) RETURNS TEXT LANGUAGE sql IMMUTABLE AS $$
    SELECT replace(replace(replace(replace(pg_temp.guild_names(t),
        '{trigger}', '{msg_trigger}'),
        '{date}', '{msg_date}'),
        '{time}', '{msg_time}'),
        '{weekday}', '{msg_weekday}')
$$;

