CREATE INDEX ON var_rename (key);

CREATE OR REPLACE FUNCTION pg_temp.bot_names(k TEXT, m JSONB) RETURNS JSONB LANGUAGE plpgsql AS $$
DECLARE
    t TEXT := pg_temp.guild_names(m::text);
    r RECORD;
BEGIN
    FOR r IN SELECT old, new FROM var_rename WHERE key = k LOOP
        t := replace(t, '{' || r.old || '}', '{' || r.new || '}');
    END LOOP;
    RETURN t::jsonb;
END $$;

-- A server's edited bot messages, and the ones a revert keeps for Undo.
-- Each row is renamed once, and only a row that changes is written.
UPDATE bot_messages b SET message = n.m
FROM (SELECT guild_id, key, pg_temp.bot_names(key, message) AS m FROM bot_messages
      WHERE key IN (SELECT key FROM var_rename) OR strpos(message::text, '{server.') > 0) n
WHERE b.guild_id = n.guild_id AND b.key = n.key AND n.m <> b.message;
UPDATE bot_messages_undo b SET message = n.m
FROM (SELECT guild_id, key, pg_temp.bot_names(key, message) AS m FROM bot_messages_undo
      WHERE key IN (SELECT key FROM var_rename) OR strpos(message::text, '{server.') > 0) n
WHERE b.guild_id = n.guild_id AND b.key = n.key AND n.m <> b.message;

-- A feed's own edited version: one message (RSS, YouTube) or one per event (GitHub, GitLab).
UPDATE feeds SET message = pg_temp.bot_names('feed.' || kind, message)
WHERE kind IN ('rss', 'youtube') AND jsonb_typeof(message) = 'object'
  AND pg_temp.bot_names('feed.' || kind, message) <> message;
UPDATE feeds SET message = (
    SELECT jsonb_object_agg(e.key, pg_temp.bot_names('feed.github.' || e.key, e.value))
    FROM jsonb_each(message) e)
WHERE kind IN ('github', 'gitlab') AND jsonb_typeof(message) = 'object' AND message <> '{}';

-- Message Builder messages and their posted copies.
UPDATE embeds SET message = pg_temp.builder_names(message::text)::jsonb
WHERE message IS NOT NULL AND pg_temp.builder_names(message::text)::jsonb <> message;
UPDATE embeds SET published = pg_temp.builder_names(published::text)::jsonb
WHERE published IS NOT NULL AND pg_temp.builder_names(published::text)::jsonb <> published;
UPDATE message_sends SET body = pg_temp.builder_names(body::text)::jsonb
WHERE pg_temp.builder_names(body::text)::jsonb <> body;
-- A message backup's Message Builder part only: its bot messages are renamed when the backup is
-- loaded (`msgbackup.rs`, `to_public`).
UPDATE backups SET messages = jsonb_set(messages, '{embeds}', pg_temp.builder_names((messages -> 'embeds')::text)::jsonb)
WHERE jsonb_typeof(messages -> 'embeds') = 'array'
  AND pg_temp.builder_names((messages -> 'embeds')::text) <> (messages -> 'embeds')::text;

-- Ticket greeting, closing and snippet texts, in every version of the settings (a revert to an
-- old version must not bring the old names back).
UPDATE guild_config SET config = jsonb_set(config, '{tickets}', replace(replace(replace(replace(
        (config -> 'tickets')::text,
        '{usermention}', '{member}'),
        '{username}', '{member.username}'),
        '{userid}', '{member.id}'),
        '{ticket_type}', '{tk_type}')::jsonb)
WHERE jsonb_typeof(config -> 'tickets') = 'object'
  AND (config -> 'tickets')::text ~ '\{(usermention|username|userid|ticket_type)\}';

